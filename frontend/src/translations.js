export function translateUiText(value, language) {
  if (language !== "hi" || typeof value !== "string" || value.length === 0) {
    return value;
  }

  const leading = value.match(/^\s*/)?.[0] || "";
  const trailing = value.match(/\s*$/)?.[0] || "";
  const source = value.trim();
  if (!source) return value;

  const exact = HINDI_TRANSLATIONS[source];
  if (exact) return `${leading}${exact}${trailing}`;

  for (const [pattern, formatter] of DYNAMIC_HINDI) {
    const match = source.match(pattern);
    if (match) return `${leading}${formatter(match)}${trailing}`;
  }

  // English is the canonical fallback for every missing key.
  return value;
}
